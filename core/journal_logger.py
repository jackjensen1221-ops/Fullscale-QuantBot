import os
import json
from datetime import datetime

class JournalLogger:
    @staticmethod
    def write_daily_journal(intel, raw_signals, validated_orders, executed_orders, equity):
        print("📝 [Journal Logger]: Generating daily research & trade journal...")
        
        timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
        
        journal_content = f"""# 📊 QuantFund Daily Research & Trade Journal
**Timestamp:** `{timestamp}`  
**Account Equity:** `${equity:,.2f}`

---

## 🧠 1. Morning Research Briefing (Market Intelligence)
* **Macro Regime:** `{intel.get('market_regime', {}).get('regime', 'UNKNOWN')}` (SPY 20d Return: `{intel.get('market_regime', {}).get('spy_20d_return', 0.0)*100:.2f}%`)
* **Volatility State:** `{intel.get('volatility_state', {}).get('state', 'NORMAL')}` (Realized Vol: `{intel.get('volatility_state', {}).get('realized_vol', 0.0)*100:.1f}%`)
* **Volume Catalyst Anomalies Detected:** `{len(intel.get('catalysts', []))}` tickers flagged.

### Catalyst Breakdown:
"""
        
        catalysts = intel.get('catalysts', [])
        if catalysts:
            for cat in catalysts:
                journal_content += f"- **{cat['symbol']}**: Volume Surge `+{cat['volume_surge_pct']:.1f}%`\n"
        else:
            journal_content += "- *No significant volume anomalies flagged today.*\n"

        journal_content += f"""
---

## 🔍 2. Strategy Signals & Decision Rationale
Total raw signals generated across active desks: **{len(raw_signals)}**

| Symbol | Strategy Desk | Signal | Proposed Weight | Status / Reasoning |
| :--- | :--- | :---: | :---: | :--- |
"""

        # Map what happened to each raw signal
        executed_symbols = {o['symbol'] for o in executed_orders}
        validated_symbols = {o['symbol'] for o in validated_orders}

        for sig in raw_signals:
            sym = sig['symbol']
            strat = sig['strategy']
            side = sig['signal']
            weight = sig.get('target_weight', 0.01)
            
            if sym in executed_symbols:
                status = "✅ **Executed** (Passed Risk & TCA)"
            elif sym in validated_symbols:
                status = "⚠️ **Filtered by TCA** (Exceeded ADV limit)"
            else:
                status = "🚫 **Filtered by Risk** (Covariance/Exposure cap)"
                
            journal_content += f"| **{sym}** | `{strat}` | **{side}** | `{weight*100:.1f}%` | {status} |\n"

        journal_content += f"""
---

## 🚀 3. Final Executed Trades
Total orders routed to Alpaca paper broker: **{len(executed_orders)}**

"""
        if executed_orders:
            for order in executed_orders:
                journal_content += f"- **{order['signal']} {order['symbol']}** | Allocation: `${order.get('allocation', 0):,.2f}` | Strategy: `{order.get('strategy')}`\n"
        else:
            journal_content += "*No orders met execution criteria during this cycle.*  \n"

        journal_content += """
---
*Automated report generated by QuantFund Core Engine.*
"""

        # Overwrite or save as latest trade journal
        with open("trade_journal.md", "w") as f:
            f.write(journal_content)
            
        print("✅ [Journal Logger]: `trade_journal.md` successfully updated.")
